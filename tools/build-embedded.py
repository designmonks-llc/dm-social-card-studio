#!/usr/bin/env python3
"""Regenerate js/embedded-assets.js from the images in assets/images/.

The studio draws every template layer onto a canvas and then exports that canvas
as PNG. When index.html is opened straight from disk (file://), browsers treat a
local image file as cross-origin, so drawing it would "taint" the canvas and
block the export. Inlining the images as base64 data URIs avoids that, so the
tool works both when you double-click index.html and when it's hosted.

Each image is stored under its file name without the extension, which is the
key js/app.js uses in META (for example assets/images/welcome_bleed.webp is
EMBED["welcome_bleed"]).

Run after adding or replacing any image:  python3 tools/build-embedded.py
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MIME = {".webp": "image/webp", ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg"}

lines = [
    "// Generated by tools/build-embedded.py from the files in assets/images/. Do not edit by hand.",
    "const EMBED = {",
]
for path in sorted((ROOT / "assets/images").iterdir()):
    if path.suffix.lower() not in MIME:
        continue
    data = base64.b64encode(path.read_bytes()).decode("ascii")
    lines.append(f'  "{path.stem}": "data:{MIME[path.suffix.lower()]};base64,{data}",')
lines.append("};")
(ROOT / "js/embedded-assets.js").write_text("\n".join(lines) + "\n")
print("wrote js/embedded-assets.js")
